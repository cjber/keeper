/**
 * Render the AUR PKGBUILD and .SRCINFO for both packages of one release.
 *
 *   bun scripts/render-aur.ts --version 0.2.0 --sha256 <hex> --bin-x64-sha256 <hex> --bin-arm64-sha256 <hex> --out aur
 *
 * The sha256 is of GitHub's tag tarball. .SRCINFO is written directly because the Ubuntu runner has no makepkg;
 * check-binary-package.sh compares both against `makepkg --printsrcinfo` on Arch.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseArgs } from "node:util";

const pkgdesc = "Agent-first cleanup for Arch: stale worktrees, AUR clones, caches and agent leftovers";
const url = "https://github.com/cjber/keeper";
const depends = ["git", "pacman-contrib"];
const optdepends = [
  "github-cli: prove a worktree finished from its merged pull request",
  "expac: size orphaned packages",
  "libnotify: desktop notifications for low disk and pending approvals",
  "uv: prune the uv cache",
];
const quoted = (items: readonly string[]) => items.map((item) => `'${item}'`).join(" ");
const hex = /^[0-9a-f]{64}$/;

function header(name: string, version: string, needs: readonly string[], conflict: string): string {
  return `# Maintainer: cjber <cjberragan at gmail dot com>
# Generated by ${url}/blob/main/scripts/render-aur.ts; edits are overwritten on the next release.
pkgname=${name}
pkgver=${version}
pkgrel=1
pkgdesc="${pkgdesc}"
arch=('x86_64' 'aarch64')
url="${url}"
license=('MIT')
depends=(${quoted(needs)})
optdepends=(${quoted(optdepends)})
provides=('keeper')
conflicts=('${conflict}')
options=('!strip')
`;
}

function info(name: string, version: string, needs: readonly string[], conflict: string, sources: string[]): string {
  return `${[
    `pkgbase = ${name}`,
    `\tpkgdesc = ${pkgdesc}`,
    `\tpkgver = ${version}`,
    "\tpkgrel = 1",
    `\turl = ${url}`,
    "\tarch = x86_64",
    "\tarch = aarch64",
    "\tlicense = MIT",
    ...needs.map((item) => `\tdepends = ${item}`),
    ...optdepends.map((item) => `\toptdepends = ${item}`),
    "\tprovides = keeper",
    `\tconflicts = ${conflict}`,
    "\toptions = !strip",
    ...sources,
    "",
    `pkgname = ${name}`,
  ].join("\n")}\n`;
}

function sourcePackage(version: string, sha256: string): { build: string; srcinfo: string } {
  const name = "keeper";
  const needs = ["bun", ...depends];
  const build = `${header(name, version, needs, "keeper-bin")}source=("\${pkgname}-\${pkgver}.tar.gz::${url}/archive/refs/tags/v\${pkgver}.tar.gz")
sha256sums=('${sha256}')

build() {
  cd "keeper-\${pkgver}"
  bun install --frozen-lockfile --production
}

package() {
  cd "keeper-\${pkgver}"
  install -d "\${pkgdir}/usr/lib/keeper" "\${pkgdir}/usr/bin"
  cp -a src skills node_modules package.json "\${pkgdir}/usr/lib/keeper/"
  ln -s /usr/lib/keeper/src/index.tsx "\${pkgdir}/usr/bin/keeper"
  install -Dm644 LICENSE "\${pkgdir}/usr/share/licenses/\${pkgname}/LICENSE"
  install -Dm644 README.md "\${pkgdir}/usr/share/doc/\${pkgname}/README.md"
}
`;
  const sources = [
    `\tsource = keeper-${version}.tar.gz::${url}/archive/refs/tags/v${version}.tar.gz`,
    `\tsha256sums = ${sha256}`,
  ];
  return { build, srcinfo: info(name, version, needs, "keeper-bin", sources) };
}

function binaryPackage(
  version: string,
  sha256: string,
  x64: string,
  arm64: string,
): { build: string; srcinfo: string } {
  const name = "keeper-bin";
  const release = `${url}/releases/download/v`;
  const build = `${header(name, version, depends, "keeper")}source=("keeper-\${pkgver}.tar.gz::${url}/archive/refs/tags/v\${pkgver}.tar.gz")
sha256sums=('${sha256}')
source_x86_64=("keeper-linux-x64-\${pkgver}::${release}\${pkgver}/keeper-linux-x64")
sha256sums_x86_64=('${x64}')
source_aarch64=("keeper-linux-arm64-\${pkgver}::${release}\${pkgver}/keeper-linux-arm64")
sha256sums_aarch64=('${arm64}')

package() {
  local binary=keeper-linux-x64
  if [[ "$CARCH" == aarch64 ]]; then binary=keeper-linux-arm64; fi
  install -Dm755 "$binary-\${pkgver}" "\${pkgdir}/usr/bin/keeper"
  install -Dm644 "keeper-\${pkgver}/LICENSE" "\${pkgdir}/usr/share/licenses/\${pkgname}/LICENSE"
  install -Dm644 "keeper-\${pkgver}/README.md" "\${pkgdir}/usr/share/doc/\${pkgname}/README.md"
  cp -a "keeper-\${pkgver}/skills" "\${pkgdir}/usr/share/doc/\${pkgname}/"
}
`;
  const sources = [
    `\tsource = keeper-${version}.tar.gz::${url}/archive/refs/tags/v${version}.tar.gz`,
    `\tsha256sums = ${sha256}`,
    `\tsource_x86_64 = keeper-linux-x64-${version}::${release}${version}/keeper-linux-x64`,
    `\tsha256sums_x86_64 = ${x64}`,
    `\tsource_aarch64 = keeper-linux-arm64-${version}::${release}${version}/keeper-linux-arm64`,
    `\tsha256sums_aarch64 = ${arm64}`,
  ];
  return { build, srcinfo: info(name, version, depends, "keeper", sources) };
}

const { values } = parseArgs({
  options: {
    version: { type: "string" },
    sha256: { type: "string" },
    out: { type: "string" },
    "bin-x64-sha256": { type: "string" },
    "bin-arm64-sha256": { type: "string" },
  },
});
const { version, sha256, out } = values;
const x64 = values["bin-x64-sha256"];
const arm64 = values["bin-arm64-sha256"];
if (!version || !/^\d+\.\d+\.\d+$/.test(version)) throw new Error(`--version must be X.Y.Z, got ${version}`);
if (!out) throw new Error("--out is required");
if (![sha256, x64, arm64].every((hash) => hash && hex.test(hash)))
  throw new Error("every digest must be 64 hex characters");
for (const [directory, rendered] of [
  [out, sourcePackage(version, sha256 as string)],
  [join(out, "bin"), binaryPackage(version, sha256 as string, x64 as string, arm64 as string)],
] as const) {
  mkdirSync(directory, { recursive: true });
  writeFileSync(join(directory, "PKGBUILD"), rendered.build);
  writeFileSync(join(directory, ".SRCINFO"), rendered.srcinfo);
}
